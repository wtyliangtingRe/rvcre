import json
from datetime import datetime, timezone
from pathlib import Path


def timestamp() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def write_json(path: Path, value: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    temporary.replace(path)


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def item_path(root: Path, identifier: str, filename: str) -> Path:
    # IDs are generated by this application. Keep API identifiers separate from file paths.
    if len(identifier) != 12 or any(c not in "0123456789abcdef" for c in identifier):
        raise ValueError("无效的声音或任务编号。")
    path = root / identifier / filename
    if not path.is_file():
        raise FileNotFoundError(f"未找到记录：{identifier}")
    return path
